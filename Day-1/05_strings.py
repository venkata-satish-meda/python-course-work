# Day 1 - Strings
# A string is text written inside quotes.

first_name = "Alex"
message = "Learning Python is fun!"

print(first_name)
print(message)

# Strings can be joined using +.
full_message = first_name + " is learning Python."
print(full_message)

# len() gives the number of characters in a string.
word = "Python"
print(len(word))

# A string can be written using single or double quotes.
single_quote = 'Hello'
double_quote = "Hello"

print(single_quote)
print(double_quote)
