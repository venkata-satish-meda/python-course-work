# Day 1 - Data Types
# A data type tells us what kind of value we are working with.

name = "Alex"       # str: text
age = 20            # int: whole number
height = 5.8        # float: decimal number
is_student = True   # bool: True or False

print(name)
print(age)
print(height)
print(is_student)

# type() shows the data type of a value.
print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
