# Day 1 - Numbers
# Python has different types of numbers, such as integers and decimals.

age = 20
marks = 85.5

print(age)
print(marks)

# Integers are whole numbers.
number1 = 10
number2 = 5

print(number1 + number2)
print(number1 - number2)
print(number1 * number2)
print(number1 / number2)

# Decimal numbers are called floats.
price = 99.50
print(price)
