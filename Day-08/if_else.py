# if-else decisions

balance = 5000
withdrawal = 6500
if withdrawal <= balance:
    balance -= withdrawal
    print("Withdrawal successful")
else:
    print("Insufficient balance")

marks = 38
if marks >= 40:
    print("Pass")
else:
    print("Needs improvement")

stock = 0
if stock > 0:
    print("Item available")
else:
    print("Out of stock")
